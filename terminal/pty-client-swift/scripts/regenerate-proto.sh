#!/usr/bin/env bash
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
package="$root/terminal/pty-client-swift"
plugin="${PROTOC_GEN_SWIFT:-protoc-gen-swift}"

mkdir -p "$package/Sources/PtyClientSwift/Generated"
tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT

protoc \
    --plugin="protoc-gen-swift=$plugin" \
    --swift_out="$tmpdir" \
    --proto_path="$root/terminal/pty-manager/proto" \
    "$root/terminal/pty-manager/proto/pty.proto"

generated="$tmpdir/pty.pb.swift"
outdir="$package/Sources/PtyClientSwift/Generated"
header='// DO NOT EDIT.
// swift-format-ignore-file
// swiftlint:disable all
//
// Generated by the Swift generator plugin for the protocol buffer compiler.
// Source: pty.proto

#if canImport(FoundationEssentials)
import FoundationEssentials
#else
import Foundation
#endif
import SwiftProtobuf
'

runtime_marker_line="$(grep -n -m1 '^// MARK: - Code below here is support for the SwiftProtobuf runtime\.$' "$generated" | cut -d: -f1)"
runtime_start_line="$(awk -v marker="$runtime_marker_line" '
    NR > marker && /^nonisolated extension .*: SwiftProtobuf\._ProtoNameProviding \{$/ {
        print NR
        exit
    }
' "$generated")"
messages_start_line="$(grep -n -m1 '^nonisolated extension Pty_V1_Hello:' "$generated" | cut -d: -f1)"
package_line="$(grep -m1 '^fileprivate nonisolated let _protobuf_package' "$generated" | sed 's/fileprivate nonisolated let _protobuf_package/nonisolated let _protobuf_package/')"

if [[ -z "$runtime_start_line" ]]; then
    echo "failed to locate generated enum runtime support" >&2
    exit 1
fi

declarations_end_line=$((runtime_marker_line - 1))
envelope_end_line=$((messages_start_line - 2))

sed -n "1,${declarations_end_line}p" "$generated" > "$outdir/PtyDeclarations.pb.swift"
printf "\n%s\n" "$package_line" >> "$outdir/PtyDeclarations.pb.swift"
printf "%s\n" "$header" > "$outdir/PtyEnvelope.pb.swift"
sed -n "${runtime_start_line},${envelope_end_line}p" "$generated" >> "$outdir/PtyEnvelope.pb.swift"
printf "%s\n" "$header" > "$outdir/PtyMessages.pb.swift"
sed -n "${messages_start_line},\$p" "$generated" >> "$outdir/PtyMessages.pb.swift"
