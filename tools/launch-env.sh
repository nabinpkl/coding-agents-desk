usage() {
    echo "usage: tools/launch-env.sh set|unset" >&2
    exit 64
}

action="${1:-}"
case "$action" in
    set|unset) ;;
    *) usage ;;
esac

set_if_present() {
    name="$1"
    value="$(printenv "$name" 2>/dev/null || true)"
    [ -n "$value" ] || return 0
    launchctl setenv "$name" "$value"
}

unset_if_present() {
    name="$1"
    value="$(printenv "$name" 2>/dev/null || true)"
    [ -n "$value" ] || return 0
    launchctl unsetenv "$name"
}

apply_name() {
    case "$action" in
        set) set_if_present "$1" ;;
        unset) unset_if_present "$1" ;;
    esac
}

for name in $fixed_names; do
    apply_name "$name"
done
