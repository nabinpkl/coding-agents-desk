#!/usr/bin/env python3
"""Generate the Swift CMUdict-to-model-phone mapping from one JSON source."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys


SOURCE = Path("client/voice-phone-calibration/arpabet-model-phone-map.json")
OUTPUT = Path(
    "client/AgentDeskClient/VoiceARPABETPhoneMapping.generated.swift"
)


def render(document: dict[str, object]) -> str:
    if document.get("schemaVersion") != 1:
        raise RuntimeError("Unsupported phone mapping schema")
    source = document.get("source")
    revision = document.get("sourceRevision")
    product_phones = document.get("productPhones")
    mapping = document.get("mapping")
    if (
        not isinstance(source, str)
        or not source
        or not isinstance(revision, str)
        or not revision
        or not isinstance(product_phones, list)
        or not product_phones
        or not all(isinstance(phone, str) and phone for phone in product_phones)
        or len(set(product_phones)) != len(product_phones)
        or not isinstance(mapping, dict)
        or not mapping
        or not all(
            isinstance(key, str)
            and key
            and isinstance(value, str)
            and value
            for key, value in mapping.items()
        )
    ):
        raise RuntimeError("Phone mapping source is malformed")
    entries = "\n".join(
        f'        {json.dumps(key, ensure_ascii=False)}: '
        f'{json.dumps(value, ensure_ascii=False)},'
        for key, value in sorted(mapping.items())
    )
    product_entries = ", ".join(
        json.dumps(phone, ensure_ascii=False) for phone in product_phones
    )
    return f"""// Generated by tools/generate-voice-phone-mapping.py. Do not edit by hand.

import Foundation

enum VoiceARPABETPhoneMapping {{
    static let source = {json.dumps(source)}
    static let sourceRevision = {json.dumps(revision)}
    static let productPhones: Set<String> = [{product_entries}]

    private static let mapping: [String: String] = [
{entries}
    ]

    static func modelPhone(for arpabet: String) -> String? {{
        mapping[arpabet]
    }}

    static let assessmentPhones: [String] =
        Array(Set(mapping.values)).sorted()
}}
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    repo_root = Path(__file__).resolve().parents[1]
    expected = render(
        json.loads((repo_root / SOURCE).read_text(encoding="utf-8"))
    )
    destination = repo_root / OUTPUT
    if args.check:
        if not destination.exists() or destination.read_text(
            encoding="utf-8"
        ) != expected:
            print(
                "Generated phone mapping is stale; run: "
                "just voice-phone-mapping",
                file=sys.stderr,
            )
            return 1
        return 0
    destination.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
