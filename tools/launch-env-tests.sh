#!/usr/bin/env sh
set -eu

tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT

cat > "$tmpdir/launchctl" <<'SH'
#!/usr/bin/env sh
printf '%s\n' "$*" >> "$LAUNCHCTL_LOG"
SH
chmod +x "$tmpdir/launchctl"

PATH="$tmpdir:$PATH"
export PATH
export LAUNCHCTL_LOG="$tmpdir/launchctl.log"

export AGENTDESK_GRAPHICS_PORT=41889
export AGENTDESK_HYBRID_SCROLL_HEVC_FPS=0
export AGENTDESK_HYBRID_SCROLL_IDLE_REFRESH_MS=250
export AGENTDESK_OWNED_MEDIA_CODEC=hevc
export AGENTDESK_OWNED_MEDIA_CHROMA=444
export AGENTDESK_OWNED_MEDIA_HEVC_PROFILE=main444
export AGENTDESK_OWNED_MEDIA_MAX_QP=24
export AGENTDESK_OWNED_MEDIA_REPAIR_DEADLINE_MS=50
export AGENTDESK_OWNED_MEDIA_RESEND_RING_FRAMES=8
export AGENTDESK_OWNED_MEDIA_MAX_RESEND_PACKETS=256
export AGENTDESK_OWNED_MEDIA_BACKPRESSURE_FRAME_AGE_MS=80
export AGENTDESK_OWNED_MEDIA_BACKPRESSURE_SEVERE_FRAME_AGE_MS=500
export AGENTDESK_OWNED_MEDIA_BACKPRESSURE_MAX_INFLIGHT_FRAMES=2
export AGENTDESK_OWNED_MEDIA_BACKPRESSURE_MAX_INFLIGHT_BYTES=300000
export AGENTDESK_OWNED_MEDIA_BACKPRESSURE_BURST_PACKET_COUNT=16
export AGENTDESK_OWNED_MEDIA_BACKPRESSURE_BURST_PAUSE_US=2500
export AGENTDESK_OWNED_MEDIA_BACKPRESSURE_ENCODE_INTERVAL_MS=67
export AGENTDESK_OWNED_MEDIA_BACKPRESSURE_SEVERE_ENCODE_INTERVAL_MS=200
export AGENTDESK_OWNED_MEDIA_DRAIN_TIMEOUT_MS=700
export AGENTDESK_OWNED_MEDIA_KEYFRAME_COOLDOWN_MS=1000
export AGENTDESK_OWNED_MEDIA_NORMAL_MAX_UNACKED_FRAMES=2
export AGENTDESK_OWNED_MEDIA_BEHIND_MAX_UNACKED_FRAMES=1
export AGENTDESK_UNRELATED=ignored

tools/launch-env.sh set
tools/launch-env.sh unset

grep -F 'setenv AGENTDESK_GRAPHICS_PORT 41889' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_HYBRID_SCROLL_HEVC_FPS 0' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_HYBRID_SCROLL_IDLE_REFRESH_MS 250' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_CODEC hevc' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_CHROMA 444' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_HEVC_PROFILE main444' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_MAX_QP 24' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_REPAIR_DEADLINE_MS 50' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_RESEND_RING_FRAMES 8' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_MAX_RESEND_PACKETS 256' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_FRAME_AGE_MS 80' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_SEVERE_FRAME_AGE_MS 500' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_MAX_INFLIGHT_FRAMES 2' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_MAX_INFLIGHT_BYTES 300000' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_BURST_PACKET_COUNT 16' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_BURST_PAUSE_US 2500' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_ENCODE_INTERVAL_MS 67' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_SEVERE_ENCODE_INTERVAL_MS 200' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_DRAIN_TIMEOUT_MS 700' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_KEYFRAME_COOLDOWN_MS 1000' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_NORMAL_MAX_UNACKED_FRAMES 2' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'setenv AGENTDESK_OWNED_MEDIA_BEHIND_MAX_UNACKED_FRAMES 1' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_GRAPHICS_PORT' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_HYBRID_SCROLL_HEVC_FPS' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_HYBRID_SCROLL_IDLE_REFRESH_MS' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_CODEC' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_CHROMA' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_HEVC_PROFILE' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_MAX_QP' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_REPAIR_DEADLINE_MS' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_RESEND_RING_FRAMES' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_MAX_RESEND_PACKETS' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_FRAME_AGE_MS' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_SEVERE_FRAME_AGE_MS' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_MAX_INFLIGHT_FRAMES' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_MAX_INFLIGHT_BYTES' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_BURST_PACKET_COUNT' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_BURST_PAUSE_US' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_ENCODE_INTERVAL_MS' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_BACKPRESSURE_SEVERE_ENCODE_INTERVAL_MS' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_DRAIN_TIMEOUT_MS' "$LAUNCHCTL_LOG" >/dev/null
