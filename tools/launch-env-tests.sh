grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_NORMAL_MAX_UNACKED_FRAMES' "$LAUNCHCTL_LOG" >/dev/null
grep -F 'unsetenv AGENTDESK_OWNED_MEDIA_BEHIND_MAX_UNACKED_FRAMES' "$LAUNCHCTL_LOG" >/dev/null

if grep -F 'AGENTDESK_UNRELATED' "$LAUNCHCTL_LOG" >/dev/null; then
    echo "unrelated AGENTDESK var was forwarded" >&2
    exit 1
fi
