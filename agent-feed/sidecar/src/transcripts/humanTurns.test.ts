import { expect, test } from "bun:test";
import type { ActivityBlock, ActivityEvent } from "@/transcripts/transcriptTypes";
import { isHarnessUserText, isHumanTurnStart } from "@/transcripts/humanTurns";

function userEvent(blocks: ActivityBlock[]): ActivityEvent {
  return { id: "e", index: 0, revision: 0, phase: "complete", ts: 0, type: "user", blocks };
}

function prose(text: string): ActivityEvent {
  return userEvent([{ kind: "text", text }]);
}

test("a person's message starts a turn", () => {
  expect(isHumanTurnStart(prose("stream the trace live"))).toBe(true);
  expect(isHumanTurnStart(prose("no its opencode go endpoint not zen"))).toBe(true);
});

test("a tool result does not, though the harness records it as a user line", () => {
  // The bug this module exists for. Sampled from one real page: 32 of 120 events were
  // `type: "user"` and every one of them was the output of something the agent ran.
  const result = userEvent([
    { kind: "tool_result", text: "File created successfully at: /Users/dev/a.ts" },
    { kind: "metadata", label: "Duration", text: "12ms" },
  ]);
  expect(result.type).toBe("user");
  expect(isHumanTurnStart(result)).toBe(false);
});

test("the harness's own envelopes do not start a turn", () => {
  // Each observed in a real transcript. `/compact` is the one that mattered most: its stdout
  // reads as ordinary prose, so a compaction became the start of a "turn" that contained
  // nothing, and the digest for it described the compaction notice as the person speaking.
  for (const text of [
    "<local-command-caveat>Caveat: The messages below were generated by the user…",
    "<command-name>/compact</command-name>",
    "<local-command-stdout>Compacted </local-command-stdout>",
    "<task-notification><task-id>b0z7ignt8</task-id>",
    "<system-reminder>As you answer the user's questions…",
    "[Request interrupted by user]",
    "[no content]",
    "Caveat: The messages below were generated by the user while running local commands.",
    "# AGENTS.md instructions for /Users/dev/projects/evals",
  ]) {
    expect(isHumanTurnStart(prose(text)), text.slice(0, 40)).toBe(false);
  }
});

test("a person writing ABOUT an envelope still starts a turn", () => {
  // Anchored patterns, not substring matches. Someone asking why a system reminder appeared is
  // asking a question, and losing their message would put the turn boundary in the wrong place
  // for exactly the conversation most likely to be about this bug.
  expect(isHumanTurnStart(prose("why is <system-reminder> showing up in the feed?"))).toBe(true);
  expect(isHumanTurnStart(prose("the <command-name> envelope should be hidden"))).toBe(true);
});

test("an assistant message never starts a turn, whatever it contains", () => {
  const assistant: ActivityEvent = { ...prose("stream the trace live"), type: "assistant" };
  expect(isHumanTurnStart(assistant)).toBe(false);
});

test("an empty or blank user event does not start a turn", () => {
  expect(isHumanTurnStart(userEvent([]))).toBe(false);
  expect(isHumanTurnStart(prose("   \n  "))).toBe(false);
});

test("the text test is exported on its own, because two callers ask it of raw strings", () => {
  expect(isHarnessUserText("<task-notification>x")).toBe(true);
  expect(isHarnessUserText("commit both suitably")).toBe(false);
});
