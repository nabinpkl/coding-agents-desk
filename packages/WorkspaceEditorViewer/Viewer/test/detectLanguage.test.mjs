import { test } from 'node:test'
import assert from 'node:assert/strict'

import { detectLanguage } from '../src/detectLanguage.mjs'

const nameOf = (name, text) => detectLanguage(name, text)?.name ?? null

test('known extension matches by filename first (regression)', () => {
  assert.equal(nameOf('app.ts', 'const x = 1'), 'TypeScript')
  assert.equal(nameOf('README.md', '# hi'), 'Markdown')
})

test('lockfile content is detected as its real format', () => {
  const cargo = '# This file is automatically @generated by Cargo.\n[[package]]\nname = "serde"\n'
  assert.equal(nameOf('Cargo.lock', cargo), 'TOML')
  assert.equal(nameOf('flake.lock', '{\n  "nodes": {}\n}\n'), 'JSON')
})

test('shebang detects an extension-less script', () => {
  assert.equal(nameOf('build', '#!/usr/bin/env python3\nprint(1)\n'), 'Python')
  assert.equal(nameOf('deploy', '#!/bin/bash\nset -e\n'), 'Shell')
  assert.equal(nameOf('run', '#!/usr/bin/env node\nconsole.log(1)\n'), 'JavaScript')
})

test('xml-family content (plist, csproj) is detected as XML', () => {
  assert.equal(nameOf('config.plist', '<?xml version="1.0"?>\n<plist><dict/></plist>\n'), 'XML')
  assert.equal(nameOf('App.csproj', '<Project Sdk="Microsoft.NET.Sdk">\n</Project>\n'), 'XML')
})

test('json content is detected', () => {
  assert.equal(nameOf('data', '{ "a": 1 }'), 'JSON')
})

test('justfiles resolve to the bundled Just mode', () => {
  assert.equal(nameOf('justfile', 'build:\n\tcargo build\n'), 'Just')
  assert.equal(nameOf('.justfile', 'x := "1"\n'), 'Just')
  assert.equal(nameOf('deploy.just', 'deploy:\n\techo hi\n'), 'Just')
})

test('no grammar and no signal returns null (caller uses the generic floor)', () => {
  assert.equal(nameOf('mystery', 'just some prose with no code shape'), null)
})
