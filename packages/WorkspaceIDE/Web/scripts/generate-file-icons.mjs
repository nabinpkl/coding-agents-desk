// Regenerates src/generated/fileIcons.mjs from the material-icon-theme package.
//
// The upstream theme carries 1250 icons (1MB of SVG). Inlining all of it would triple the IDE
// bundle for icons nobody sees, so this subsets by *icon*, not by extension: name the families
// worth carrying and every extension and filename upstream maps to them comes along for free
// (`html` alone pulls htm, xhtml, asp, ...). Anything outside the set falls back to the plain
// document glyph the sidebar already drew.
//
// Run `npm run icons` after bumping material-icon-theme. The output is committed so the bundle
// build and `node --test` stay dependency-free.

import { readFile, readdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'

const require = createRequire(import.meta.url)

/// Icon families worth their bytes: the languages, configs, and media a person actually opens,
/// plus the ones this repo is built out of. Add a name here, run the script, review the diff.
const includedIcons = [
  // Languages
  'swift', 'objective-c', 'objective-cpp',
  'typescript', 'react_ts', 'javascript', 'react', 'nodejs', 'vue', 'svelte', 'astro',
  'python', 'rust', 'go', 'ruby', 'java', 'kotlin', 'scala', 'dart', 'lua', 'php', 'csharp',
  'c', 'h', 'cpp', 'hpp', 'haskell', 'elixir', 'erlang', 'clojure', 'julia', 'r', 'zig',
  'perl', 'nim', 'ocaml', 'vim', 'assembly',
  // Markup, styles, data
  'html', 'css', 'sass', 'less', 'tailwindcss', 'markdown', 'mdx', 'tex',
  'json', 'yaml', 'toml', 'xml', 'graphql', 'proto', 'database',
  // Config and tooling
  'settings', 'git', 'docker', 'kubernetes', 'terraform', 'nginx', 'makefile', 'just',
  'tsconfig', 'eslint', 'prettier', 'npm', 'yarn', 'lock', 'tune', 'key', 'certificate',
  'console', 'powershell', 'nix', 'gradle', 'cmake',
  // Documents and media
  'readme', 'license', 'pdf', 'word', 'powerpoint', 'table', 'document', 'jupyter',
  'image', 'svg', 'video', 'audio', 'font', 'zip', 'log', 'exe',
]

/// Upstream ships light and high-contrast variants of a few icons. The sidebar uses one icon per
/// file in both schemes (the colours are mid-saturation and read on either background), so the
/// variants are dead weight.
const isVariant = (name) => name.endsWith('_light') || name.endsWith('_highContrast')

function svgBody(markup, name) {
  const open = markup.match(/<svg\b[^>]*>/)
  if (!open) throw new Error(`no <svg> element in ${name}.svg`)
  const viewBox = open[0].match(/viewBox="([^"]+)"/)
  if (!viewBox) throw new Error(`no viewBox in ${name}.svg`)
  const body = markup
    .slice(open.index + open[0].length, markup.lastIndexOf('</svg>'))
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    // A handful of icons define gradients as `id="a"`. Every icon lands inline in one document,
    // so an unprefixed `a` would let whichever icon rendered first capture every `url(#a)` on the
    // page. Prefixing by icon name confines each definition to its own artwork.
    .replace(/\bid="([^"]+)"/g, `id="${name}-$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${name}-$1)`)
  if (!body) throw new Error(`empty <svg> in ${name}.svg`)
  return { viewBox: viewBox[1], body }
}

/// Invert upstream's `{ extension: iconName }` map, keeping only the icons we carry. Upstream
/// keys are already lowercase; the runtime lowercases the filename before looking it up.
function mappingFor(source, kept) {
  return Object.fromEntries(
    Object.entries(source)
      .filter(([, icon]) => kept.has(icon))
      .sort(([left], [right]) => (left < right ? -1 : 1))
  )
}

function serialize(value) {
  const key = (name) => (/^[a-z][a-z0-9]*$/i.test(name) ? name : JSON.stringify(name))
  const entries = Object.entries(value)
    .map(([name, entry]) => `  ${key(name)}: ${JSON.stringify(entry)},`)
    .join('\n')
  return `Object.freeze({\n${entries}\n})`
}

const manifestPath = require.resolve('material-icon-theme/dist/material-icons.json')
const packageRoot = resolve(dirname(manifestPath), '..')
const { version } = require('material-icon-theme/package.json')
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))

const available = new Set(
  (await readdir(resolve(packageRoot, 'icons')))
    .filter((name) => name.endsWith('.svg'))
    .map((name) => name.slice(0, -4))
)
const missing = includedIcons.filter((name) => !available.has(name))
if (missing.length) throw new Error(`material-icon-theme has no icon named: ${missing.join(', ')}`)

const kept = new Set(includedIcons.filter((name) => !isVariant(name)))
const shapes = {}
for (const name of [...kept].sort()) {
  shapes[name] = svgBody(await readFile(resolve(packageRoot, 'icons', `${name}.svg`), 'utf8'), name)
}

const generated = `// Generated by scripts/generate-file-icons.mjs from material-icon-theme@${version} (MIT,
// (c) Material Extensions — see LICENSE.material-icon-theme). Do not edit; run \`npm run icons\`.

export const iconShapes = ${serialize(shapes)}

export const extensionIcons = ${serialize(mappingFor(manifest.fileExtensions, kept))}

export const filenameIcons = ${serialize(mappingFor(manifest.fileNames, kept))}
`

const outputPath = resolve(import.meta.dirname, '..', 'src', 'generated', 'fileIcons.ts')
await writeFile(outputPath, generated)
await writeFile(
  resolve(import.meta.dirname, '..', 'LICENSE.material-icon-theme'),
  await readFile(resolve(packageRoot, 'LICENSE'), 'utf8')
)
console.log(
  `fileIcons.mjs: ${kept.size} icons, `
  + `${Object.keys(mappingFor(manifest.fileExtensions, kept)).length} extensions, `
  + `${Object.keys(mappingFor(manifest.fileNames, kept)).length} filenames, `
  + `${generated.length} bytes`
)
